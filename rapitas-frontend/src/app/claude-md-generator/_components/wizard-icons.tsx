interface WizardIconProps {
  /** lucide icon name stored in the catalog / カタログに格納された lucide アイコン名 */
  name: string;
  /** pixel size / ピクセルサイズ */
  size?: number;
}

/**
 * Renders the lucide icon registered under `name`. Falls back to a neutral
 * Box glyph for unknown names so a typo never crashes the wizard.
 *
 * @param props - WizardIconProps / WizardIconProps参照
 */
export function WizardIcon({ name, size = 18 }: WizardIconProps) {
  const Icon = REGISTRY[name] || Box;
  return <Icon size={size} strokeWidth={1.75} />;
}

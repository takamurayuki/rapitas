#!/usr/bin/env node
/**
 * generate-postgres-init-sql
 *
 * Writes src/generated/postgres-init-sql.ts: the PostgreSQL DDL for an empty
 * database, from prisma/schema. It is what the "initialize" action applies to
 * a user's own cloud database (#1285) — explicitly, once, instead of the
 * `prisma db push` dev.js runs on every start, which must never be pointed at
 * a user's database. `prisma migrate diff` reads the schema only; it touches
 * no database.
 */
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const backendDir = path.resolve(__dirname, '..');
const schemaDir = path.join(backendDir, 'prisma', 'schema');
const outputFile = path.join(backendDir, 'src', 'generated', 'postgres-init-sql.ts');

function escapeTemplateLiteral(value) {
  return value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

try {
  const sql = execFileSync(
    'bunx',
    ['prisma', 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', schemaDir, '--script'],
    {
      cwd: backendDir,
      encoding: 'utf8',
      env: {
        ...process.env,
        // migrate diff never connects; the URL only satisfies config parsing.
        DATABASE_URL: 'postgresql://unused:unused@localhost:5432/unused',
      },
    },
  );
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(
    outputFile,
    [
      '// Generated by scripts/generate-postgres-init-sql.cjs. Do not edit manually.',
      'export const POSTGRES_INIT_SQL = String.raw`',
      escapeTemplateLiteral(sql.trim()),
      '`;',
      '',
    ].join('\n'),
  );
  console.log(`Generated PostgreSQL init SQL: ${outputFile}`);
} catch (error) {
  console.error('Failed to generate PostgreSQL init SQL');
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
